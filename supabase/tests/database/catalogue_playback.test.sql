select throws_ok($$select public.save_title((select id from tests.ids where label='public'),'movie','Bad country','Description',0,null,null,null,null,array['bad'])$$,'P0001','invalid_country','country restrictions require ISO codes');
select tests.act('other');
select throws_ok($$select public.save_season((select id from tests.ids where label='series'),2,'stolen')$$,'42501','publisher_required','other users cannot modify a series');
