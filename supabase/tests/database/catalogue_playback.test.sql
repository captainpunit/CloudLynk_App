select tests.act('guest');
select is((select count(*) from public.seasons),0::bigint,'unreviewed season metadata is not public');
select tests.act('creator');
select throws_ok($$select public.submit_title_review((select id from tests.ids where label='movie'))$$,'P0001','video_processing','unprocessed video cannot enter review');
